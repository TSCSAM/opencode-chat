const RELATIVE: Record<Lang, Intl.RelativeTimeFormat> = {
  en: new Intl.RelativeTimeFormat("en", { numeric: "auto" }),
  fa: new Intl.RelativeTimeFormat("fa", { numeric: "auto" }),
}

const NUMBER: Record<Lang, Intl.NumberFormat> = {
  en: new Intl.NumberFormat("en-US"),
  fa: new Intl.NumberFormat("fa-IR"),
}

type Vars = Record<string, string | number | undefined | null>

export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "fa"
}

export function readLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY)
    if (isLang(saved)) return saved
  } catch {}
  return "en"
}

export function applyDocumentLang(lang: Lang) {
  if (typeof document === "undefined") return
  document.documentElement.lang = lang
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr"
  document.documentElement.dataset.lang = lang
}

export function translate(lang: Lang, text: string, vars?: Vars): string {
  const template = lang === "fa" ? FA[text] ?? text : text
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = vars[key]
    return value === undefined || value === null ? "" : String(value)
  })
}

export function formatNumber(lang: Lang, value: number | undefined | null): string {
  if (!Number.isFinite(value as number)) return "—"
  return NUMBER[lang].format(value as number)
}

export function formatRelative(lang: Lang, timestamp: number): string {
  const diff = (timestamp - Date.now()) / 1000
  const abs = Math.abs(diff)
  if (abs < 60) return RELATIVE[lang].format(Math.round(diff), "second")
  if (abs < 3600) return RELATIVE[lang].format(Math.round(diff / 60), "minute")
  if (abs < 86400) return RELATIVE[lang].format(Math.round(diff / 3600), "hour")
  return RELATIVE[lang].format(Math.round(diff / 86400), "day")
}

type I18nContextValue = {
  lang: Lang
  dir: Direction
  locale: string
  setLang: (lang: Lang) => void
  toggleLang: () => void
  t: (text: string, vars?: Vars) => string
  num: (value: number | undefined | null) => string
  relative: (timestamp: number) => string
  time: (timestamp: number) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readLang())

  useEffect(() => {
    applyDocumentLang(lang)
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang)
    } catch {}
  }, [lang])

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    applyDocumentLang(next)
    try {
      localStorage.setItem(LANG_STORAGE_KEY, next)
    } catch {}
  }, [])

  const value = useMemo<I18nContextValue>(() => {
    const t = (text: string, vars?: Vars) => translate(lang, text, vars)
    return {
      lang,
      dir: lang === "fa" ? "rtl" : "ltr",
      locale: lang === "fa" ? "fa-IR" : "en-US",
      setLang,
      toggleLang: () => setLang(lang === "fa" ? "en" : "fa"),
      t,
      num: (n) => formatNumber(lang, n),
      relative: (ts) => formatRelative(lang, ts),
      time: (ts) =>
        new Date(ts).toLocaleTimeString(lang === "fa" ? "fa-IR" : "en-US", {
          hour: "2-digit",
          minute: "2-digit",
          second: "2-digit",
        }),
    }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error("useI18n must be used inside I18nProvider")
  return value
}
